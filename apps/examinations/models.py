from django.db import models
from django.core.validators import MinValueValidator, MaxValueValidator

from apps.core.models import BaseModel


class AssessmentType(BaseModel):
    """
    Defines the assessment categories used by the university,
    such as Quiz, Assignment, Mid, and Final.
    """

    name = models.CharField(
        max_length=50,
        unique=True,
    )

    code = models.CharField(
        max_length=20,
        unique=True,
        help_text="Unique system code (e.g. QUIZ, ASSIGNMENT, MID, FINAL).",
    )

    description = models.TextField(blank=True)

    is_active = models.BooleanField(default=True)

    class Meta:
        ordering = ["id"]
        verbose_name = "Assessment Type"
        verbose_name_plural = "Assessment Types"

    def __str__(self):
        return self.name


class AssessmentPolicy(BaseModel):
    """
    Defines the assessment policy for an academic term,
    including the number of assessments and their overall weightage.
    """

    term = models.ForeignKey(
        "academics.Term",
        on_delete=models.CASCADE,
        related_name="assessment_policies",
    )

    assessment_type = models.ForeignKey(
        AssessmentType,
        on_delete=models.PROTECT,
        related_name="policies",
    )

    number_of_assessments = models.PositiveSmallIntegerField(
        default=1,
        validators=[MinValueValidator(1)],
        help_text="Number of assessments (e.g. 4 quizzes, 2 mids).",
    )

    total_weightage = models.DecimalField(
        max_digits=5,
        decimal_places=2,
        validators=[
            MinValueValidator(0),
            MaxValueValidator(100),
        ],
        help_text="Overall percentage contribution of this assessment type toward the final course grade.",
    )

    class Meta:
        ordering = ["assessment_type"]
        verbose_name = "Assessment Policy"
        verbose_name_plural = "Assessment Policies"

        constraints = [
            models.UniqueConstraint(
                fields=["term", "assessment_type"],
                name="unique_assessment_policy",
            )
        ]

    def __str__(self):
        return f"{self.term} - {self.assessment_type.name}"


class Assessment(BaseModel):
    """
    Represents an assessment for a course offering.

    Assessment records are automatically generated by the system
    according to the assessment policy. Faculty members later enter
    the assessment date, total marks and students' obtained marks.
    """

    course_offering = models.ForeignKey(
        "academics.CourseOffering",
        on_delete=models.CASCADE,
        related_name="assessments",
    )

    assessment_type = models.ForeignKey(
        AssessmentType,
        on_delete=models.PROTECT,
        related_name="assessments",
    )

    sequence_number = models.PositiveSmallIntegerField(
        validators=[MinValueValidator(1)],
        help_text="Sequence number (e.g. Quiz 1, Quiz 2, Mid 1).",
    )

    assessment_date = models.DateField(
        null=True,
        blank=True,
        help_text="Date on which the assessment was conducted.",
    )

    total_marks = models.PositiveIntegerField(
        null=True,
        blank=True,
        validators=[MinValueValidator(1)],
        help_text="Total marks entered by the faculty.",
    )

    marks_submitted = models.BooleanField(
        default=False,
        help_text="Indicates whether the faculty has finalized marks submission.",
    )

    class Meta:
        ordering = [
            "course_offering",
            "assessment_type",
            "sequence_number",
        ]
        verbose_name = "Assessment"
        verbose_name_plural = "Assessments"

        constraints = [
            models.UniqueConstraint(
                fields=[
                    "course_offering",
                    "assessment_type",
                    "sequence_number",
                ],
                name="unique_assessment_per_course_offering",
            )
        ]

    @property
    def title(self):
        """
        Returns the display title.

        Examples:
            Quiz 1
            Quiz 2
            Assignment 1
            Mid 1
            Final
        """

        if self.assessment_type.code.upper() == "FINAL":
            return self.assessment_type.name

        return f"{self.assessment_type.name} {self.sequence_number}"

    def __str__(self):
        return f"{self.course_offering} - {self.title}"


class StudentAssessment(BaseModel):
    """
    Stores the marks obtained by a student in a specific assessment.
    """

    assessment = models.ForeignKey(
        Assessment,
        on_delete=models.CASCADE,
        related_name="student_assessments",
    )

    student = models.ForeignKey(
        "profiles.StudentProfile",
        on_delete=models.CASCADE,
        related_name="assessment_results",
    )

    obtained_marks = models.DecimalField(
        max_digits=5,
        decimal_places=2,
        null=True,
        blank=True,
        validators=[MinValueValidator(0)],
        help_text="Marks obtained by the student.",
    )

    remarks = models.TextField(blank=True)

    class Meta:
        ordering = [
            "assessment",
            "student",
        ]
        verbose_name = "Student Assessment"
        verbose_name_plural = "Student Assessments"

        constraints = [
            models.UniqueConstraint(
                fields=["assessment", "student"],
                name="unique_student_assessment",
            )
        ]

    def __str__(self):
        return f"{self.student} - {self.assessment.title}"



class GradePolicy(BaseModel):
    """
    Defines the grading policy for an academic term.
    """

    term = models.OneToOneField(
        "academics.Term",
        on_delete=models.CASCADE,
        related_name="grade_policy",
    )

    name = models.CharField(max_length=100)

    description = models.TextField(blank=True)



class GradeScale(BaseModel):
    """
    Defines each grade within a grading policy.
    """

    grade_policy = models.ForeignKey(
        GradePolicy,
        on_delete=models.CASCADE,
        related_name="grade_scales",
    )

    grade = models.CharField(max_length=2)

    min_percentage = models.DecimalField(max_digits=5, decimal_places=2)

    max_percentage = models.DecimalField(max_digits=5, decimal_places=2)

    grade_points = models.DecimalField(max_digits=3, decimal_places=2)

    remarks = models.CharField(
        max_length=50,
        blank=True,
    )

    class Meta:
        ordering = ["-min_percentage"]